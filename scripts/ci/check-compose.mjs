#!/usr/bin/env node
// Static hardening assertions on the merged compose configuration (PRD-0003 SK-2 AC1 "compose-config", SK-16 AC2 and AC3).
// Usage: docker compose -f deploy/compose.yaml -f deploy/compose.e2e.yaml config --format json | node scripts/ci/check-compose.mjs
// Every deviation from the rules needs an entry in EXCEPTIONS with a reason; the exceptions are reviewed with the owner (CODEOWNERS).
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const MB = 1024 * 1024;

/** Memory budget per service in bytes (PRD-0003 SK-16 AC2); an override may lower a limit but never raise it. */
export const BUDGET = {
  'core-backend': 1536 * MB,
  'reference-module': 768 * MB,
  keycloak: 1536 * MB,
  postgres: 2048 * MB,
  proxy: 256 * MB,
  ldap: 256 * MB,
};

/** service -> rule -> reason. */
export const EXCEPTIONS = {
  keycloak: {
    readOnly: 'the server writes its import and temporary files below /opt/keycloak/data',
    user: 'the image runs as uid 1000 by default',
  },
  ldap: {
    readOnly: 'test directory image writes configuration at start',
    user: 'test directory image starts as root and drops privileges itself',
    healthcheck: 'nothing depends on it; the scenario that uses it waits for the port',
    digest: 'digest to be pinned when the federation scenario is enabled',
    capDrop: 'the image needs a few capabilities to initialise (added back explicitly)',
  },
};

/** Environment names that look like secrets, with the reason a literal value is allowed. */
export const SECRET_ENV_ALLOWED = {
  E2E_USER_PASSWORD: 'per-run test credential of the e2e realm, generated by deploy/scripts/gen-secrets.sh',
};

const SECRET_NAME = /(PASSWORD|SECRET|TOKEN)/;

function excepted(service, rule) {
  return Boolean(EXCEPTIONS[service]?.[rule]);
}

function bytes(value) {
  if (typeof value === 'number') return value;
  const match = /^(\d+)([kmg]?)b?$/i.exec(String(value ?? ''));
  if (!match) return undefined;
  const factor = { '': 1, k: 1024, m: MB, g: 1024 * MB }[match[2].toLowerCase()];
  return Number(match[1]) * factor;
}

function environmentOf(service) {
  const env = service.environment ?? {};
  return Array.isArray(env) ? Object.fromEntries(env.map((e) => e.split(/=(.*)/s).slice(0, 2))) : env;
}

/** Returns the list of problems found in a compose configuration (the parsed `config --format json` output). */
export function check(config) {
  const problems = [];
  const services = config.services ?? {};
  if (Object.keys(services).length === 0) problems.push('no services in the compose configuration');
  for (const [name, service] of Object.entries(services)) {
    const where = `service ${name}`;
    const capDrop = (service.cap_drop ?? []).map((c) => String(c).toUpperCase());
    if (!capDrop.includes('ALL') && !excepted(name, 'capDrop')) problems.push(`${where}: cap_drop must contain ALL`);
    if (!(service.security_opt ?? []).some((o) => String(o).startsWith('no-new-privileges'))) problems.push(`${where}: security_opt must contain no-new-privileges`);
    if (service.privileged) problems.push(`${where}: privileged is not allowed`);
    if (['host'].includes(service.network_mode) || service.pid === 'host' || service.ipc === 'host') problems.push(`${where}: host namespaces are not allowed`);
    for (const volume of service.volumes ?? []) {
      const source = typeof volume === 'string' ? volume.split(':')[0] : volume.source;
      if (String(source).includes('docker.sock')) problems.push(`${where}: the Docker socket must not be mounted`);
    }
    if (!service.pids_limit) problems.push(`${where}: pids_limit is missing`);
    const memory = bytes(service.mem_limit);
    if (!memory) problems.push(`${where}: mem_limit is missing`);
    else if (BUDGET[name] && memory > BUDGET[name]) problems.push(`${where}: mem_limit ${memory} exceeds the budget ${BUDGET[name]}`);
    else if (!BUDGET[name]) problems.push(`${where}: no memory budget is defined for this service`);
    if (!service.cpus) problems.push(`${where}: cpus is missing`);
    const logging = service.logging ?? {};
    if (logging.driver !== 'json-file' || logging.options?.['max-size'] !== '10m' || String(logging.options?.['max-file']) !== '5') {
      problems.push(`${where}: logging must be json-file with max-size 10m and max-file 5`);
    }
    if (!service.read_only && !excepted(name, 'readOnly')) problems.push(`${where}: read_only must be true`);
    const user = String(service.user ?? '');
    if ((user === '' || user === '0' || user.startsWith('0:') || user === 'root') && !excepted(name, 'user')) problems.push(`${where}: must run as a non-root user`);
    if (!service.healthcheck && !excepted(name, 'healthcheck')) problems.push(`${where}: healthcheck is missing`);
    if (service.image && !service.build && !String(service.image).includes('@sha256:') && !excepted(name, 'digest')) {
      problems.push(`${where}: image ${service.image} must be pinned by digest`);
    }
    for (const port of service.ports ?? []) {
      const published = String(typeof port === 'string' ? port.split(':').slice(0, -1).pop() : port.published);
      if (name !== 'proxy' || published !== '443') problems.push(`${where}: publishes port ${published}; only the proxy may publish 443`);
    }
    for (const [key, value] of Object.entries(environmentOf(service))) {
      if (SECRET_NAME.test(key) && !key.endsWith('_FILE') && value && !SECRET_ENV_ALLOWED[key]) {
        problems.push(`${where}: environment ${key} holds a literal value; use a secret file (${key}_FILE)`);
      }
    }
  }
  for (const [name, secret] of Object.entries(config.secrets ?? {})) {
    if (secret.environment || secret.content) problems.push(`secret ${name}: must come from a file`);
  }
  return problems;
}

function main() {
  const input = readFileSync(0, 'utf8');
  const problems = check(JSON.parse(input));
  if (problems.length > 0) {
    console.error(problems.map((p) => `- ${p}`).join('\n'));
    process.exit(1);
  }
  console.log('compose configuration meets the hardening rules');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
