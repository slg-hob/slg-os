// Token generator (PRD-0005 VL-5 AC1): JSON in, files out, byte-for-byte reproducible. No network, no clock, no randomness.
import { parseColor, evaluatePairs, ROLE_THRESHOLDS } from './contrast.mjs';
import { allPairs, colorMap } from './tokens.mjs';

export const GENERATED_HEADER = 'Generated by @slg-os/design-tools from design/tokens/*.json. Do not edit; run "npm run tokens:generate" in frontend/.';

/** Selectors of the themes (see ADR-0023 for the specificity reasoning). */
const LIGHT = ':root,\n[data-bs-theme="light"]';
const DARK = '[data-bs-theme="dark"]';
const HC_LIGHT = ':root:not([data-bs-theme="dark"]),\n[data-bs-theme="light"]';
const FORCED = ':root:not([data-bs-theme="dark"]),\n[data-bs-theme="light"],\n[data-bs-theme="dark"]';

const rem = (px) => `${Number((px / 16).toFixed(4))}rem`;
const pxValue = (px) => `${px}px`;
const channels = (value) => {
  const { r, g, b } = parseColor(value);
  return `${r}, ${g}, ${b}`;
};
const isOpaque = (value) => parseColor(value).a === 1;

/** Custom properties of one theme for the colour and shadow tokens. `pick` selects the value; undefined skips the token. */
function themeDeclarations(sources, pickColor, pickShadow) {
  const lines = [];
  for (const c of sources.color) {
    const value = pickColor(c);
    if (value === undefined) continue;
    lines.push(`  --slg-${c.name}: ${value};`);
    if (isOpaque(value)) lines.push(`  --slg-${c.name}-rgb: ${channels(value)};`);
  }
  for (const s of sources.shadow) {
    const value = pickShadow(s);
    if (value !== undefined) lines.push(`  --slg-${s.name}: ${value};`);
  }
  return lines;
}

const block = (selector, lines, indent = '') =>
  [`${indent}${selector.split('\n').join(`\n${indent}`)} {`, ...lines.map((l) => `${indent}${l}`), `${indent}}`].join('\n');

/** tokens.css: all custom properties, themes, high contrast and forced colours. */
export function generateTokensCss(sources) {
  const fixed = [];
  for (const t of sources.type) {
    if (t.kind === 'family') fixed.push(`  --slg-${t.name}: ${t.value};`);
    else {
      fixed.push(`  --slg-type-${t.name}-size: ${rem(t.size)};`);
      fixed.push(`  --slg-type-${t.name}-line: ${rem(t.lineHeight)};`);
      fixed.push(`  --slg-type-${t.name}-weight: ${t.weight};`);
    }
  }
  for (const s of sources.space) fixed.push(`  --slg-${s.name}: ${rem(s.px)};`);
  for (const r of sources.radius) fixed.push(`  --slg-${r.name}: ${pxValue(r.px)};`);
  for (const s of sources.size) fixed.push(`  --slg-${s.name}: ${pxValue(s.px)};`);
  for (const m of sources.motion) fixed.push(`  --slg-${m.name}: ${m.value};`);

  const out = [`/* ${GENERATED_HEADER} */`];
  out.push(block(LIGHT, ['  color-scheme: light;', ...fixed, ...themeDeclarations(sources, (c) => c.light, (s) => s.light)]));
  out.push(block(DARK, ['  color-scheme: dark;', ...themeDeclarations(sources, (c) => c.dark, (s) => s.dark)]));
  out.push(`@media (prefers-contrast: more) {\n${[
    block(HC_LIGHT, themeDeclarations(sources, (c) => c.lightHc, () => undefined), '  '),
    block(DARK, themeDeclarations(sources, (c) => c.darkHc, () => undefined), '  '),
  ].join('\n')}\n}`);
  const forced = [];
  for (const c of sources.color) if (c.forced) forced.push(`  --slg-${c.name}: ${c.forced};`);
  for (const s of sources.shadow) if (s.forced) forced.push(`  --slg-${s.name}: ${s.forced};`);
  out.push(`@media (forced-colors: active) {\n${block(FORCED, forced, '  ')}\n}`);
  return `${out.join('\n\n')}\n`;
}

/** bootstrap-map.css: sets the runtime --bs-* variables from the --slg-* tokens (VL-5 AC2). */
export function generateBootstrapMapCss(sources) {
  const lines = sources.bootstrap.entries.map((e) => `  ${e.bs}: var(--slg-${e.token}${e.channels ? '-rgb' : ''});`);
  const selector = ':root,\n[data-bs-theme="light"],\n[data-bs-theme="dark"]';
  return `/* ${GENERATED_HEADER} */\n${block(selector, lines)}\n`;
}

const scssString = (value) => `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;

/** _tokens.scss: Sass maps for the Bootstrap build. */
export function generateScss(sources) {
  const map = (name, entries) => `$${name}: (\n${entries.map(([k, v]) => `  '${k}': ${v},`).join('\n')}\n);`;
  const parts = [`// ${GENERATED_HEADER}`];
  parts.push(map('slg-colors-light', sources.color.map((c) => [c.name, c.light])));
  parts.push(map('slg-colors-dark', sources.color.map((c) => [c.name, c.dark])));
  parts.push(map('slg-fonts', sources.type.filter((t) => t.kind === 'family').map((t) => [t.name, scssString(t.value)])));
  parts.push(map('slg-type', sources.type.filter((t) => t.kind === 'scale').map((t) => [t.name,
    `(size: ${rem(t.size)}, line: ${rem(t.lineHeight)}, weight: ${t.weight})`])));
  parts.push(map('slg-space', sources.space.map((s) => [s.name, rem(s.px)])));
  parts.push(map('slg-radius', sources.radius.map((r) => [r.name, pxValue(r.px)])));
  parts.push(map('slg-shadow-light', sources.shadow.map((s) => [s.name, scssString(s.light)])));
  parts.push(map('slg-shadow-dark', sources.shadow.map((s) => [s.name, scssString(s.dark)])));
  return `${parts.join('\n\n')}\n`;
}

/** tokens.ts: typed constants for components and tests. */
export function generateTypeScript(sources) {
  const lines = [`// ${GENERATED_HEADER}`, ''];
  lines.push('export const colorTokens = {');
  for (const c of sources.color) lines.push(`  '${c.name}': { light: '${c.light}', dark: '${c.dark}' },`);
  lines.push('} as const;', '', 'export type ColorTokenName = keyof typeof colorTokens;', '');
  const named = (key, field) => sources[key].map((e) => `  '${e.name}': '${field(e)}',`);
  lines.push('export const spaceTokens = {', ...named('space', (e) => rem(e.px)), '} as const;', '');
  lines.push('export const radiusTokens = {', ...named('radius', (e) => pxValue(e.px)), '} as const;', '');
  lines.push('export const sizeTokens = {', ...named('size', (e) => pxValue(e.px)), '} as const;', '');
  lines.push('export const motionTokens = {', ...named('motion', (e) => e.value), '} as const;', '');
  lines.push('export const typeScale = {');
  for (const t of sources.type.filter((e) => e.kind === 'scale')) {
    lines.push(`  '${t.name}': { size: '${rem(t.size)}', line: '${rem(t.lineHeight)}', weight: ${t.weight} },`);
  }
  lines.push('} as const;', '');
  lines.push('/** Name of the CSS custom property that carries a token. */', 'export const cssVar = (name: string): string => `--slg-${name}`;', '');
  return lines.join('\n');
}

/** pairs.json: the contrast pair list, for the computed-style checks of later milestones. */
export function generatePairList(sources) {
  const pairs = allPairs(sources).map((pair) => ({
    id: pair.id,
    foreground: `--slg-${pair.fg}`,
    background: `--slg-${pair.bg}`,
    role: pair.role,
    threshold: ROLE_THRESHOLDS[pair.role],
    ...(pair.over ? { over: pair.over.map((o) => (o === 'black' || o === 'white' ? o : `--slg-${o}`)) } : {}),
  }));
  return `${JSON.stringify(pairs, null, 2)}\n`;
}

/** Throws when a pair of the sources fails; used by the generator so a failing token set never produces output. */
export function assertPairsPass(sources) {
  const failing = evaluatePairs(colorMap(sources), allPairs(sources)).filter((r) => !r.pass);
  if (failing.length > 0) throw new Error(`${failing.length} contrast pair(s) below threshold; run the contrast check`);
}

/**
 * All generated files by path relative to the design-system package ("src/generated/...").
 * @returns {Map<string, string>}
 */
export function generateAll(sources) {
  return new Map([
    ['src/generated/tokens.css', generateTokensCss(sources)],
    ['src/generated/bootstrap-map.css', generateBootstrapMapCss(sources)],
    ['src/generated/_tokens.scss', generateScss(sources)],
    ['src/generated/tokens.ts', generateTypeScript(sources)],
    ['src/generated/pairs.json', generatePairList(sources)],
  ]);
}
