// Command line of the design tools. The bin wrappers only pass process arguments and paths; all logic is here so it is testable.
//   generate  validate the sources and write src/generated/* of the design-system package
//   check     tokens-sync: regenerate in memory and fail when the committed files differ (git diff --exit-code equivalent)
//   contrast  evaluate every declared pair; exit 1 when one is below its threshold
//   styles    compile dist/design-system.css (tokens + Bootstrap from SCSS) and check the gzip budget
//   assets    verify docs/design/assets.lock against the lock file, hashes, licences and THIRD-PARTY-NOTICES
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { evaluatePairs, formatFailures } from './contrast.mjs';
import { generateAll } from './generate.mjs';
import { verifyAssets } from './assets-lock.mjs';
import { findUnmappedBootstrapVariables, readSources } from './bootstrap-usage.mjs';
import { buildStyles, checkBudget, findForbiddenUrls } from './styles.mjs';
import { allPairs, colorMap, loadSources, validateSources } from './tokens.mjs';

const GENERATED_DIR = 'src/generated';

function loadValid(designDir, err) {
  const model = loadSources(designDir);
  const problems = validateSources(model);
  if (problems.length > 0) {
    err(`invalid token sources:\n${problems.map((p) => `- ${p}`).join('\n')}`);
    return undefined;
  }
  return model.sources;
}

/**
 * @param {string[]} argv command and arguments
 * @param {{designDir: string, packageDir: string, repoRoot: string, lockFile: string, packageLockFile: string, noticesFile: string,
 *          out?: (line: string) => void, err?: (line: string) => void}} env
 * @returns {number} exit code
 */
export function run(argv, env) {
  const out = env.out ?? ((line) => process.stdout.write(`${line}\n`));
  const err = env.err ?? ((line) => process.stderr.write(`${line}\n`));
  const [command] = argv;
  try {
    switch (command) {
      case 'generate': return generate(env, out, err);
      case 'check': return checkSync(env, out, err);
      case 'contrast': return contrast(env, out, err);
      case 'styles': return styles(env, out, err);
      case 'assets': return assets(env, out, err);
      default:
        err('usage: design-tools <generate|check|contrast|styles|assets>');
        return 2;
    }
  } catch (error) {
    err(`error: ${error.message}`);
    return 1;
  }
}

function generate(env, out, err) {
  const sources = loadValid(env.designDir, err);
  if (!sources) return 1;
  const files = generateAll(sources);
  for (const [path, content] of files) {
    const target = join(env.packageDir, path);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, content);
  }
  out(`generated ${files.size} files in ${join(env.packageDir, GENERATED_DIR)}`);
  return 0;
}

function checkSync(env, out, err) {
  const sources = loadValid(env.designDir, err);
  if (!sources) return 1;
  const files = generateAll(sources);
  const problems = [];
  for (const [path, content] of files) {
    const target = join(env.packageDir, path);
    if (!existsSync(target)) problems.push(`${path} is missing`);
    else if (readFileSync(target, 'utf8') !== content) problems.push(`${path} differs from the generated output`);
  }
  const dir = join(env.packageDir, GENERATED_DIR);
  const expected = new Set([...files.keys()].map((p) => p.slice(GENERATED_DIR.length + 1)));
  if (existsSync(dir)) {
    for (const name of readdirSync(dir)) if (!expected.has(name)) problems.push(`${GENERATED_DIR}/${name} is not generated by the current sources`);
  }
  const mapped = new Set(sources.bootstrap.entries.map((e) => e.bs));
  for (const dir of env.platformSourceDirs ?? []) problems.push(...findUnmappedBootstrapVariables(readSources(dir), mapped));
  if (problems.length > 0) {
    err(`tokens-sync failed (run "npm run tokens:generate" in frontend/ and commit the result):\n${problems.map((p) => `- ${p}`).join('\n')}`);
    return 1;
  }
  out(`tokens-sync passed (${files.size} generated files match the sources)`);
  return 0;
}

function contrast(env, out, err) {
  const sources = loadValid(env.designDir, err);
  if (!sources) return 1;
  const results = evaluatePairs(colorMap(sources), allPairs(sources));
  const failures = formatFailures(results);
  if (failures.length > 0) {
    err(`contrast check failed for ${failures.length} of ${results.length} evaluations:\n${failures.map((f) => `- ${f}`).join('\n')}`);
    return 1;
  }
  out(`contrast check passed (${results.length} evaluations of ${allPairs(sources).length} pairs in 4 modes)`);
  return 0;
}

function styles(env, out, err) {
  const { css, file, gzipBytes } = buildStyles(env.packageDir);
  const problems = [checkBudget(css), ...findForbiddenUrls(css)].filter(Boolean);
  if (problems.length > 0) {
    err(`styles check failed:\n${problems.map((p) => `- ${p}`).join('\n')}`);
    return 1;
  }
  out(`built ${file} (${(gzipBytes / 1024).toFixed(1)} KB gzip)`);
  return 0;
}

function assets(env, out, err) {
  const problems = verifyAssets({
    lock: JSON.parse(readFileSync(env.lockFile, 'utf8')),
    packageLock: JSON.parse(readFileSync(env.packageLockFile, 'utf8')),
    repoRoot: env.repoRoot,
    notices: readFileSync(env.noticesFile, 'utf8'),
  });
  if (problems.length > 0) {
    err(`assets check failed:\n${problems.map((p) => `- ${p}`).join('\n')}`);
    return 1;
  }
  out('assets check passed (hashes, licences and notices match)');
  return 0;
}
